import { randomBytes } from "node:crypto";

/** Dedicated, non-production PostgreSQL instance used only by the 5c runner. */
export const PG_TEST_IMAGE = "postgres:16-alpine";
export const TEST_DATABASE = "e_pig_5c";
export const TEST_USER = "e_pig_test";
export const LOOPBACK_HOST = "127.0.0.1";
export const TEST_MARKER = "E_PIG_AFTER_SALES_PG_TEST";
export const TEST_CONTAINER_MARKER = "E_PIG_AFTER_SALES_PG_CONTAINER";

const INHERITED_DATABASE_ENV = new Set([
  "DATABASE_URL",
  "NEON_DATABASE_URL",
  TEST_MARKER,
  TEST_CONTAINER_MARKER,
]);
const INHERITED_PREFIXES = ["PG", "POSTGRES_", "E_PIG_AFTER_SALES_PG_"];

/**
 * The runner owns the instance identity. Names and labels are deterministic
 * from the random id so cleanup can target exactly one container.
 */
export function createInstanceIdentity(random = randomBytes) {
  const id = random(8).toString("hex");
  if (!/^[0-9a-f]{16}$/.test(id)) {
    throw new Error("Instance id must be 16 lowercase hex characters");
  }
  return {
    id,
    containerName: `e-pig-as5c-${id}`,
    instanceLabel: `e-pig.after-sales.5c.instance=${id}`,
    scopeLabel: "e-pig.after-sales.5c=true",
  };
}

/**
 * Build the child environment without any inherited database URL or PG*
 * variable. The child only receives the runner-owned loopback instance.
 */
export function buildChildEnv({
  baseEnv = process.env,
  port,
  password,
  containerName,
} = {}) {
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new Error("The dedicated PostgreSQL port must be an integer between 1 and 65535");
  }
  if (typeof password !== "string" || password.length < 16) {
    throw new Error("The dedicated PostgreSQL password must be generated by the runner");
  }
  if (typeof containerName !== "string" || !/^e-pig-as5c-[0-9a-f]{16}$/.test(containerName)) {
    throw new Error("The dedicated PostgreSQL container name is not runner-owned");
  }

  const env = {};
  for (const [name, value] of Object.entries(baseEnv)) {
    if (typeof value !== "string") continue;
    if (INHERITED_DATABASE_ENV.has(name)) continue;
    if (INHERITED_PREFIXES.some((prefix) => name.startsWith(prefix))) continue;
    env[name] = value;
  }

  return {
    ...env,
    PGHOST: LOOPBACK_HOST,
    PGPORT: String(port),
    PGDATABASE: TEST_DATABASE,
    PGUSER: TEST_USER,
    PGPASSWORD: password,
    PGSSLMODE: "disable",
    [TEST_MARKER]: "1",
    [TEST_CONTAINER_MARKER]: containerName,
  };
}

/** Docker must publish the instance on loopback only, with a single mapping. */
export function parseDockerPortOutput(output) {
  const lines = String(output ?? "").trim().split(/\r?\n/).filter(Boolean);
  if (lines.length !== 1) {
    throw new Error("Docker returned an ambiguous PostgreSQL port mapping");
  }
  const match = /^(127\.0\.0\.1):(\d{1,5})$/.exec(lines[0].trim());
  if (!match) {
    throw new Error("Docker PostgreSQL port mapping must be loopback-only (127.0.0.1)");
  }
  const port = Number(match[2]);
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new Error("Docker returned an invalid PostgreSQL port");
  }
  return { host: match[1], port };
}

/**
 * The spec calls this with values read back from the live connection. It fails
 * closed instead of continuing against an unexpected database or user.
 */
export function validateDedicatedDatabaseIdentity({
  marker,
  database,
  user,
  serverPort,
  expectedServerPort = 5432,
}) {
  if (marker !== "1") {
    throw new Error("Run the after-sales PostgreSQL spec through the dedicated runner");
  }
  if (database !== TEST_DATABASE) {
    throw new Error("The after-sales PostgreSQL spec is not connected to its dedicated database");
  }
  if (user !== TEST_USER) {
    throw new Error("The after-sales PostgreSQL spec is not connected as its dedicated user");
  }
  if (!Number.isInteger(serverPort) || serverPort !== expectedServerPort) {
    throw new Error("The after-sales PostgreSQL server port is not the dedicated container port");
  }
  return { database, user, serverPort };
}
